 const base=parseSound({version:'1.0',id:key,name:key,sampleRate:44100,durationMs:s.d,seed:1,
 voices:s.voices.map((v,j)=>({...v,id:`voice-${j}`})),effects:s.effects,output:{gain:.72,clipping:'error',fadeMs:Math.min(2,s.d/8)},export:{format:'wav-pcm16',key},metadata:{trigger:row[2].trim(),design:row[3].trim()}});
